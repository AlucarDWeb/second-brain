#!/usr/bin/env python3
"""Regenerate Concepts/_INDEX.md — the dedup lookup index — from the Concept notes.

One line per Concept: `- **[[Name]]** · `aliases` · one-line definition.`
  - Name    = the note's filename (the wikilink target)
  - aliases = the `aliases:` frontmatter list, verbatim order
  - one-liner = first sentence of the definition paragraph (the first prose
    paragraph after the `# H1`), markdown-flattened and length-capped

Deterministic and idempotent: same vault state → byte-identical index. The LLM
must never hand-write this file; `/compile` and `/lint` call this script instead.

Usage:
    python3 generate_index.py           # rewrite if changed, print summary
    python3 generate_index.py --check   # don't write; exit 1 if drifted
"""

from __future__ import annotations

import argparse
import datetime as _dt
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_views import parse_frontmatter  # noqa: E402  (shared minimal-YAML parser)

VAULT = Path(__file__).resolve().parent
CONCEPTS = VAULT / "Concepts"
INDEX = CONCEPTS / "_INDEX.md"

MAX_DEF_LEN = 300

HEADER = """\
# Concept Index (generated)

> **Do not hand-edit.** This file is regenerated by `generate_index.py`
> (run by `/compile` after each batch and reconciled by `/lint`).
> It is the **dedup lookup**: before creating a Concept, `rg` this list — names **and aliases** —
> for the incoming idea. If it's here under any name, extend that note; don't make a near-duplicate.
> One line per Concept: **Name** · `aliases` · one-line definition.
"""

WIKILINK_RE = re.compile(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]")
# Sentence boundary: terminator, whitespace, then an uppercase/quote/backtick start.
# Lowercase continuations ("e.g. the", "vs. the") don't split.
SENTENCE_END_RE = re.compile(r"(?<=[.!?])\s+(?=[A-Z\"`(\[])")


def first_paragraph(body: str) -> str:
    """First prose paragraph after the H1 — skips headings, fences, quotes, lists."""
    lines = body.splitlines()
    para: list[str] = []
    in_fence = False
    seen_h1 = False
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if stripped.startswith("# ") and not seen_h1:
            seen_h1 = True
            continue
        if not seen_h1:
            continue
        if not stripped:
            if para:
                break
            continue
        if stripped.startswith(("#", ">", "-", "*", "|", "!")):
            if para:
                break
            continue
        para.append(stripped)
    return " ".join(para)


def flatten_markdown(text: str) -> str:
    text = WIKILINK_RE.sub(lambda m: m.group(2) or m.group(1), text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"\1", text)
    text = re.sub(r"(?<!\w)\*([^*]+)\*(?!\w)", r"\1", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def one_liner(body: str) -> str:
    para = flatten_markdown(first_paragraph(body))
    if not para:
        return "(no definition paragraph)"
    if len(para) > MAX_DEF_LEN:
        para = SENTENCE_END_RE.split(para, 1)[0]
    if len(para) > MAX_DEF_LEN:
        para = para[:MAX_DEF_LEN].rsplit(" ", 1)[0].rstrip(",;:·") + " …"
    return para


def build_index(today: str, created: str) -> str:
    entries = []
    for path in sorted(CONCEPTS.glob("*.md"), key=lambda p: p.stem.casefold()):
        if path.name == "_INDEX.md":
            continue
        fm, body = parse_frontmatter(path.read_text(encoding="utf-8"))
        aliases = fm.get("aliases") or []
        if isinstance(aliases, str):
            aliases = [aliases]
        alias_str = ", ".join(a for a in aliases if a)
        alias_part = f"`{alias_str}`" if alias_str else "—"
        entries.append(f"- **[[{path.stem}]]** · {alias_part} · {one_liner(body)}")

    fm_block = (
        f"---\ntype: index\ngenerated: true\ncreated: {created}\nupdated: {today}\n---\n"
    )
    return (
        f"{fm_block}\n{HEADER}\n**Count:** {len(entries)} concepts.\n\n"
        + "\n".join(entries)
        + "\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="report drift, write nothing")
    args = ap.parse_args()

    today = _dt.date.today().isoformat()
    old = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
    created = today
    m = re.search(r"^created:\s*(\S+)", old, re.M)
    if m:
        created = m.group(1)

    new = build_index(today, created)
    count = new.count("\n- **[[")

    # Ignore the volatile `updated:` stamp when deciding whether anything changed.
    def _stable(text: str) -> str:
        return re.sub(r"^updated:.*$", "", text, flags=re.M)

    if _stable(new) == _stable(old):
        print(f"_INDEX.md: {count} concepts · unchanged")
        return 0

    old_titles = set(re.findall(r"^- \*\*\[\[([^\]]+)\]\]", old, re.M))
    new_titles = set(re.findall(r"^- \*\*\[\[([^\]]+)\]\]", new, re.M))
    added = sorted(new_titles - old_titles)
    removed = sorted(old_titles - new_titles)
    delta = []
    if added:
        delta.append(f"+{len(added)} ({', '.join(added[:5])}{'…' if len(added) > 5 else ''})")
    if removed:
        delta.append(f"-{len(removed)} ({', '.join(removed[:5])}{'…' if len(removed) > 5 else ''})")
    changed = "; ".join(delta) if delta else "line content changed"

    if args.check:
        print(f"_INDEX.md: DRIFT — {count} concepts · {changed}")
        return 1

    INDEX.write_text(new, encoding="utf-8")
    print(f"_INDEX.md: rewritten · {count} concepts · {changed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
